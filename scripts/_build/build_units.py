def build_units():
    outdir = "_data/units"
    os.makedirs(outdir, exist_ok=True)
    # Map unitId -> list of pyqIds from both years
    pyq_map = {}
    for year, data in [("2024", Q2024), ("2025", Q2025)]:
        for (qnum, subj, unit, cat, page, stem, opts, correct, diff, tags, figkey) in data:
            qid = f"jelet-{year}-q{qnum:03d}"
            pyq_map.setdefault(unit, []).append(qid)

    for (unit_id, subj, code, title, mins, freq, sections, examples, traps) in UNITS:
        sections_out = []
        for (anchor, heading, prose, formulas) in sections:
            formula_list = []
            for (fid, label_text, latex, ctx) in formulas:
                formula_list.append({"formulaId": fid, "label": label_text, "latex": latex, "aiExplainContext": ctx})
            sections_out.append({
                "anchor": anchor, "heading": heading, "proseLatex": prose, "keyFormulas": formula_list
            })
        examples_out = []
        for (eid, problem, steps, answer) in examples:
            examples_out.append({
                "exampleId": eid, "problemLatex": problem, "stepsLatex": steps, "answerLatex": answer
            })
        unit_data = {
            "unitId": unit_id,
            "subjectId": subj,
            "officialCode": code,
            "title": title,
            "estimatedMinutes": mins,
            "examFrequency": freq,
            "pyqIds": sorted(pyq_map.get(unit_id, [])),
            "sections": sections_out,
            "workedExamples": examples_out,
            "wbjeebTraps": traps,
            "videoLectures": [],
            "practiceSetIds": [],
        }
        path = os.path.join(outdir, f"{unit_id}.json")
        with open(path, "w") as f:
            json.dump(unit_data, f, indent=2, ensure_ascii=False)
    print(f"Generated {len(UNITS)} unit files.")

if __name__ == "__main__":
    build_units()
